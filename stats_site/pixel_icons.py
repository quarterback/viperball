def _runs(grid):
    rows = [r for r in grid.strip("\n").split("\n")]
    out = {"#": [], "+": []}
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch in out:
                start = x
                while x < len(row) and row[x] == ch:
                    x += 1
                out[ch].append(f"M{start} {y}h{x - start}v1h-{x - start}z")
            else:
                x += 1
    return out


_CACHE = {name: _runs(g) for name, g in _ICONS.items()}


def icon(name, size=16, label=None, cls=""):
    """Inline SVG for a pixel icon. Size should be a multiple of 16 to stay crisp."""
    runs = _CACHE.get(name)
    if not runs:
        return Markup("")
    a11y = f'role="img" aria-label="{label}"' if label else 'aria-hidden="true"'
    parts = [f'<path fill="currentColor" d="{"".join(runs["#"])}"/>']
    if runs["+"]:
        parts.append(f'<path fill="var(--accent)" d="{"".join(runs["+"])}"/>')
    return Markup(
        f'<svg class="px-icon {cls}" width="{size}" height="{size}" viewBox="0 0 16 16" '
        f'shape-rendering="crispEdges" {a11y}>{"".join(parts)}</svg>'
    )


def names():
    return list(_ICONS)
